def luminance(value):
    rgb = [int(value.lstrip('#')[i:i+2], 16) / 255 for i in (0, 2, 4)]
    lin = [x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4 for x in rgb]
    return sum(v * w for v, w in zip(lin, (.2126, .7152, .0722)))

def ratio(a, b):
    l1, l2 = sorted((luminance(a), luminance(b)), reverse=True)
    return (l1 + .05) / (l2 + .05)

